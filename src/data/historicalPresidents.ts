  name: string,
  party: string,
  partyId: PartyId,
  yearsInOffice: string,
  priorRole: string,
  coalition: CoalitionId,
  background: BackgroundId,
  governingDoctrine: string,
  summary: string,
  vpId: string,
  jcsId: string,
  cabinet: Record<CabinetDepartment, string>
